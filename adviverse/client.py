"""Public Adviverse entry — binds generated routes as ergonomic namespaces."""
from __future__ import annotations
from ._facade import Core
try:
    from ._facade.routes import ROUTES  # generated by codegen/facade-gen.mjs
except Exception:
    ROUTES = {}

class _Namespace:
    def __init__(self, core: Core, methods: dict): self._core, self._m = core, methods
    def __getattr__(self, name):
        spec = self._m.get(name)
        if not spec: raise AttributeError(name)
        def call(**params):
            path = spec["path"]; query, body = {}, None
            for p in spec["params"]:
                if p["name"] == "body": body = params.get("body")
                elif p["in"] == "path" and p["name"] in params:
                    path = path.replace("{" + p["name"] + "}", str(params.pop(p["name"])))
                elif p["name"] in params: query[p["name"]] = params[p["name"]]
            return self._core._request(spec["httpMethod"], path, query=query or None, body=body)
        return call

class Adviverse(Core):
    def __init__(self, *a, **k):
        super().__init__(*a, **k)
        for ns, methods in ROUTES.items():
            setattr(self, ns, _Namespace(self, {mm["method"]: mm for mm in methods}))
